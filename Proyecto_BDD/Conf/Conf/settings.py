def variable_obligatoria(nombre):
    """Devuelve una variable de entorno o detiene el arranque con un mensaje claro."""
    valor = os.environ.get(nombre)
    if not valor:
        raise ImproperlyConfigured(
            f'Falta la variable {nombre}. Copie .env.example como .env y complete su valor.'
        )
    return valor


